// Search bars: find an activity (domain / sector) and a module quickly, in the wizard and in the settings screen.
const { check, launch, setup } = require('./helper');
(async () => {
  const t = await launch(), p = t.page;
  check('assistant : barre de recherche d\'activité', await p.isVisible('.wizard [data-find=act]'));
  const total = await p.locator('.wizard select[name=activity] option').count();
  await p.fill('.wizard input[name=name]', 'Ets Recherche');
  await p.fill('.wizard [data-find=act]', 'taxi');
  const hits = await p.locator('.wizard select[name=activity] option').allTextContents();
  check('recherche « taxi » : peu de résultats, dont Taxi', hits.length > 0 && hits.length < total && hits.some(h => /taxi/i.test(h)), hits.join('|'));
  await p.fill('.wizard [data-find=act]', 'PHARMACIE');
  check('recherche insensible à la casse', (await p.locator('.wizard select[name=activity] option').count()) >= 1);
  await p.fill('.wizard [data-find=act]', 'cafe');
  const cafe = await p.locator('.wizard select[name=activity] option').count();
  check('recherche insensible aux accents ou résultat vide géré', cafe >= 1);
  await p.fill('.wizard [data-find=act]', 'zzzzqq');
  check('aucun résultat : message, liste complète conservée', (await p.textContent('.finder-hint')).includes('Aucun résultat') && (await p.locator('.wizard select[name=activity] option').count()) === total);
  await p.fill('.wizard [data-find=act]', 'taxi'); await p.press('.wizard [data-find=act]', 'Enter');
  check('Entrée choisit le premier résultat', (await p.inputValue('.wizard select[name=activity]')) === 'taxi' && (await p.inputValue('.wizard [data-find=act]')) === '' && (await p.locator('.wizard select[name=activity] option').count()) === total);
  await p.click('[data-next]'); await p.click('[data-next]');
  check('étape modules : barre de recherche', await p.isVisible('.wizard [data-find=mod]'));
  const mods = await p.locator('.wizard .mod').count();
  await p.fill('.wizard [data-find=mod]', 'stock');
  const shown = await p.locator('.wizard .mod:visible').count();
  check('recherche de module filtre la liste', shown >= 1 && shown < mods, shown + '/' + mods);
  await p.fill('.wizard [data-find=mod]', 'zzzzqq');
  check('aucun module : message', await p.isVisible('.finder-none') && (await p.locator('.wizard .mod:visible').count()) === 0);
  await p.fill('.wizard [data-find=mod]', '');
  check('recherche vidée : tous les modules', (await p.locator('.wizard .mod:visible').count()) === mods);
  await p.click('[data-next]'); await p.waitForSelector('.wizard', { state: 'detached' });
  check('activité enregistrée par l\'assistant', await p.evaluate(() => App.db.settings.activity) === 'taxi');
  await p.evaluate(() => App.go('settings')); await p.waitForSelector('[data-find=act]');
  await p.fill('[data-find=act]', 'restau');
  const opts = await p.locator('select[data-p=activity] option').allTextContents();
  check('réglages : recherche d\'activité', opts.length >= 1 && opts.some(o => /restau/i.test(o)), opts.join('|'));
  await p.selectOption('select[data-p=activity]', { index: 0 });
  const chosen = await p.evaluate(() => App.db.settings.activity);
  check('réglages : choix d\'un résultat enregistré', chosen !== 'taxi' && !!await p.evaluate(a => App.PRESETS[a], chosen), chosen);
  await p.waitForSelector('[data-find=mod]');
  await p.fill('[data-find=mod]', 'stock');
  check('réglages : recherche de module', (await p.locator('.set .mod:visible').count()) >= 1);
  check('aucune erreur JS', t.errors.length === 0, t.errors.join(' | ')); await t.browser.close();
})().catch(e => { console.log('FAIL exception → ' + e.message); process.exit(1); });
